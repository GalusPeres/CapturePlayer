// Local file import regression; never loads the selected DLL into this process.
import { build } from 'esbuild';
import fs from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
const root = path.resolve(import.meta.dirname, '..');
const dir = path.join(root, '.local/neural-import-test');
await fs.mkdir(dir, { recursive: true });
await build({ entryPoints: [path.join(root, 'electron/neuralRuntime.ts')], outfile: path.join(dir, 'runtime.cjs'), bundle: true, platform: 'node', format: 'cjs' });
const { NeuralRuntimeStore, validateNeuralRuntime, SUPPORTED_NEURAL_RUNTIME } = createRequire(import.meta.url)(path.join(dir, 'runtime.cjs'));
const data = await fs.mkdtemp(path.join(dir, 'profile-'));
const store = new NeuralRuntimeStore(data);
await store.initialize(); assert.equal(store.file, undefined);
const invalidDirectory = path.join(data, 'invalid'); await fs.mkdir(invalidDirectory);
const invalid = path.join(invalidDirectory, 'nvngx_dlssnr.dll');
await fs.writeFile(invalid, 'not a DLL');
await assert.rejects(store.importFile(invalid), /Unsupported DLL/);
assert.equal(store.file, undefined);
await assert.rejects(store.importFile(path.join(invalidDirectory, 'nvngx_dlss.dll')), /not a different DLSS DLL/);
const source = path.join(root, '.local/neural-runtime/nvngx_dlssnr.dll');
const result = await store.importFile(source);
assert.equal(result.version, SUPPORTED_NEURAL_RUNTIME.version);
assert.notEqual(store.file, source);
await validateNeuralRuntime(store.file);
const imported = store.file;
const restarted = new NeuralRuntimeStore(data);
await restarted.initialize(); assert.equal(restarted.file, imported, 'Restart lost imported runtime');
await fs.copyFile(source, invalid);
const handle = await fs.open(invalid, 'r+');
await handle.write(Buffer.from([0xff]), 0, 1, 0); await handle.close();
await assert.rejects(store.importFile(invalid), /not a valid Windows DLL/);
assert.equal(store.file, imported, 'Failed import replaced the active runtime');
await fs.copyFile(source, invalid);
const corrupt = await fs.open(invalid, 'r+');
const last = Buffer.alloc(1); await corrupt.read(last, 0, 1, SUPPORTED_NEURAL_RUNTIME.bytes - 1);
last[0] ^= 0xff; await corrupt.write(last, 0, 1, SUPPORTED_NEURAL_RUNTIME.bytes - 1); await corrupt.close();
await assert.rejects(store.importFile(invalid), /differs from the tested runtime/);
assert.equal(store.file, imported);
await store.importFile(source); // Reimport uses the verified installed file.
assert.equal(store.file, imported);
assert.ok(!(await fs.readdir(data)).some(name => name.startsWith('import-')), 'Staged DLL was not cleaned up');
await fs.rm(invalid);
await fs.writeFile(path.join(dir, 'result.json'), JSON.stringify({ imported, version: result.version, passed: true }, null, 2));
console.log('PASS: valid DLL import, persisted restart, invalid filename/size/PE/hash rejection, failed-import recovery, repeated import.');
console.log('IMPORTED_DLL=' + imported);
